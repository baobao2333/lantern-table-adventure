import {readFile, readdir, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve, basename} from 'node:path';
import Ajv from 'ajv';
import {semanticErrors} from '../lib/game/content-validation.mjs';
import {worldErrors} from '../lib/game/world-validation.mjs';

const root = fileURLToPath(new URL('../',import.meta.url));
const schema = JSON.parse(await readFile(resolve(root,'content/campaign.schema.json'),'utf8'));
const validate = new Ajv({allErrors:true, strict:false}).compile(schema);
const worldValidate = new Ajv({allErrors:true, strict:false}).compile(JSON.parse(await readFile(resolve(root,'content/world.schema.json'),'utf8')));
const args = process.argv.slice(2), sync = args.includes('--sync'), candidate = args.indexOf('--file');
if (candidate >= 0 && (!args[candidate+1] || sync)) throw new Error('Use --file <candidate.json> without --sync.');
const scan = async folder => (await readdir(resolve(root,folder))).filter(f=>f.endsWith('.json')).sort().map(f=>resolve(root,folder,f));
const files = candidate >= 0 ? [resolve(args[candidate+1])] : [...await scan('content/campaigns'),...await scan('content/worlds')];
if (!files.length) throw new Error('No campaigns found.');
const ids = new Set();
for (const file of files) {
  const raw = await readFile(file,'utf8');
  let campaign;
  try {campaign = JSON.parse(raw);} catch {throw new Error(`${basename(file)}: invalid JSON`);}
  const check = campaign.format==='situation-v1'?worldValidate:validate;
  if (!check(campaign)) throw new Error(`${basename(file)}:\n${check.errors.map(e => `${e.instancePath || '/'}: ${e.message}`).join('\n')}`);
  const errors = campaign.format==='situation-v1'?worldErrors(campaign):semanticErrors(campaign);
  if (errors.length) throw new Error(`${basename(file)}:\n${errors.join('\n')}`);
  if (ids.has(campaign.id)) throw new Error(`${basename(file)}: duplicate campaign ID`);
  ids.add(campaign.id);
  if (candidate < 0 && basename(file) !== `${campaign.id}.json`) throw new Error(`${basename(file)}: filename must match campaign ID`);
  const formatted = JSON.stringify(campaign,null,2)+'\n';
  if (candidate < 0 && sync) await writeFile(file,formatted);
  else if (candidate < 0 && raw.replace(/\r\n/g,'\n') !== formatted) throw new Error(`${basename(file)}: use npm run content:sync to format the JSON`);
  console.log(`PASS ${basename(file)}: ${campaign.locations?`${campaign.locations.length} locations, ${campaign.opportunities.length} opportunities`: `${campaign.scenes.length} scenes`}, ${Object.keys(campaign.endings).length-1} story endings`);
}
if (candidate < 0) {
  for(const [folder,prefix] of [['campaigns','campaign'],['worlds','world']]) {
    const selected=files.filter(f=>f.includes(`${folder}\\`)||f.includes(`${folder}/`));
    const registry = `// Generated by content:sync. Edit content/${folder}/*.json instead.\n`+selected.map((file,i) => `import ${prefix}${i} from '../../content/${folder}/${basename(file)}' with {type:'json'};`).join('\n')+`\nexport const ${prefix}Content = [${selected.map((_,i)=>`${prefix}${i}`).join(', ')}];\n`;
    const target = resolve(root,`lib/game/${prefix}-content.generated.mjs`);
    if(sync) await writeFile(target,registry);
    else if((await readFile(target,'utf8').catch(()=> '')).replace(/\r\n/g,'\n')!==registry) throw new Error('Registry is stale. Run npm run content:sync.');
  }
}
